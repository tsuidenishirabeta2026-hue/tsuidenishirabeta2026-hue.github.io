export const SPLIT_LABELS = {
  vs_lhp: '対左投手',
  vs_rhp: '対右投手',
  vs_lhb: '対左打者',
  vs_rhb: '対右打者',
  risp: '得点圏',
};

export function splitLabel(s) {
  if (SPLIT_LABELS[s]) return SPLIT_LABELS[s];
  if (s.startsWith('stadium:')) return `球場別: ${s.slice(8)}`;
  return s;
}
